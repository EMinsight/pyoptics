def _hermite_functions(n_max, u):
    """Normalized Hermite functions h_n(u) = H_n(u) exp(-u**2/2)/sqrt(2**n n! sqrt(pi)),
    n = 0..n_max, by the stable recurrence; shape (n_max + 1,) + u.shape."""
    u = np.asarray(u, dtype=float)
    h = np.empty((n_max + 1,) + u.shape)
    h[0] = np.pi**-0.25*np.exp(-u**2/2)
    if n_max > 0:
        h[1] = np.sqrt(2.0)*u*h[0]
    for n in range(2, n_max + 1):
        h[n] = np.sqrt(2.0/n)*u*h[n - 1] - np.sqrt((n - 1)/n)*h[n - 2]
    return h


def _beam(w0, wavelength, n, distance):
    k = wavenumber(wavelength, n)
    zR = k*w0**2/2
    w = w0*np.sqrt(1 + (distance/zR)**2)
    R = np.inf if distance == 0 else distance*(1 + (zR/distance)**2)
    gouy = np.arctan2(distance, zR)
    return k, w, R, gouy


def _hg_1d(n_max, x, w0, wavelength, n_medium, distance):
    """1D HG mode amplitudes (without the curvature phase) at a distance
    from the waist, shape (n_max + 1, len(x)); each has unit power in 1D."""
    k, w, R, gouy = _beam(w0, wavelength, n_medium, distance)
    h = _hermite_functions(n_max, np.sqrt(2.0)*np.asarray(x)/w)*np.sqrt(np.sqrt(2.0)/w)
    phase = np.exp(-1j*(np.arange(n_max + 1) + 0.5)*gouy)
    return h*phase[:, None], k, R


def hermite_gauss(l, m, w0, wavelength, x, y=None, n=1.0, distance=0.0, w0_y=None,
                  polarization="x", z=0.0):
    """Hermite-Gaussian mode TEM_lm as a Field (unit power), with the Gouy
    phase and the curvature kept analytic.

    Parameters
    ----------
    l, m : int
        Orders along x and y (m ignored for one-dimensional fields).
    w0 : number
        Waist radius of the fundamental mode (along x).
    wavelength : number
    x, y : arrays
        Grid (y None: one-dimensional).
    n : number, optional
        Refractive index.
    distance : number, optional
        Distance behind the waist.
    w0_y : number, optional
        Waist radius along y (default w0): simple astigmatism.
    polarization, z : optional
        As in fieldtrace.gaussian().

    Returns
    -------
    Field
    """
    hx, k, Rx = _hg_1d(l, x, w0, wavelength, n, distance)
    ax = hx[l]
    if y is None:
        A = ax
        alpha = (0.0 if np.isinf(Rx) else k/(2*Rx), 0.0)
    else:
        hy, _, Ry = _hg_1d(m, y, w0 if w0_y is None else w0_y, wavelength, n, distance)
        A = hy[m][:, None]*ax[None, :]
        alpha = (0.0 if np.isinf(Rx) else k/(2*Rx), 0.0 if np.isinf(Ry) else k/(2*Ry))
    f = _ft.Field(A, x, y, wavelength, n, alpha=alpha,
                  jones=_ft._normalize_jones(polarization), z=z)
    return _unit_power(f)


def gsm_parameters(sigma_s, sigma_g):
    """Coherent mode decomposition of a 1D Gaussian Schell model source
    with the cross spectral density ::

        W(x1, x2) = exp(-(x1**2 + x2**2)/(4 sigma_s**2)) exp(-(x1 - x2)**2/(2 sigma_g**2)).

    The modes are Hermite-Gaussian functions with the waist w0 (1/e**2
    radius of the fundamental irradiance) and the relative weights
    kappa**n (Gori 1983, Starikov and Wolf 1982).

    Parameters
    ----------
    sigma_s : number
        Rms width of the irradiance (the 1/e**2 radius is 2*sigma_s).
    sigma_g : number
        Rms coherence width (inf: fully coherent).

    Returns
    -------
    w0 : float
        Waist radius of the modes.
    kappa : float
        Ratio of the weights of successive modes, 0 <= kappa < 1.
    """
    a = 1/(4*sigma_s**2)
    b = 0.0 if np.isinf(sigma_g) else 1/(2*sigma_g**2)
    c = np.sqrt(a**2 + 2*a*b)
    return 1/np.sqrt(c), b/(a + b + c)


def gsm_m2(sigma_s, sigma_g):
    """Beam quality of a Gaussian Schell model beam (per axis),
    M² = sqrt(1 + 4 sigma_s**2/sigma_g**2) = (1 + kappa)/(1 - kappa)."""
    return np.sqrt(1 + (2*sigma_s/sigma_g)**2)


def gsm_width(sigma_s, sigma_g, z, wavelength, n=1.0):
    """Rms width sigma(z) of a Gaussian Schell model beam a distance z from
    its waist, sigma(z)**2 = sigma_s**2 (1 + (z/z_eff)**2) with
    z_eff = 2 k sigma_s**2/M² (Mandel and Wolf, section 5.6.4)."""
    k = wavenumber(wavelength, n)
    z_eff = 2*k*sigma_s**2/gsm_m2(sigma_s, sigma_g)
    return sigma_s*np.sqrt(1 + (z/z_eff)**2)


def _hg_ensemble(w0, kappa, wavelength, x, y, n, distance, polarization, power, fraction,
                 max_order, label, info, w0_y=None, kappa_y=None):
    one_d = y is None
    kx = kappa
    ky = kappa if kappa_y is None else kappa_y

    def orders(k):
        if k <= 0:
            return 0
        n_ = int(np.ceil(np.log(1 - fraction)/np.log(k))) if fraction < 1 else max_order
        return int(min(max_order, max(n_, 0)))

    Lx = orders(kx)
    hx, kk, Rx = _hg_1d(Lx, x, w0, wavelength, n, distance)
    alpha_x = 0.0 if np.isinf(Rx) else kk/(2*Rx)
    fields, weights = [], []
    jones = _ft._normalize_jones(polarization)
    if one_d:
        for l in range(Lx + 1):
            fields.append(_ft.Field(hx[l], x, None, wavelength, n, alpha=(alpha_x, 0.0),
                                    jones=jones))
            weights.append(kx**l)
    else:
        Ly = orders(ky)
        hy, _, Ry = _hg_1d(Ly, y, w0 if w0_y is None else w0_y, wavelength, n, distance)
        alpha_y = 0.0 if np.isinf(Ry) else kk/(2*Ry)
        for l in range(Lx + 1):
            for m in range(Ly + 1):
                fields.append(_ft.Field(hy[m][:, None]*hx[l][None, :], x, y, wavelength, n,
                                        alpha=(alpha_x, alpha_y), jones=jones))
                weights.append(kx**l*ky**m)
    weights = np.array(weights)
    keep = np.argsort(-weights)
    keep = keep[:int(np.searchsorted(np.cumsum(weights[keep])/np.sum(weights[keep]),
                                     fraction*(1 - 1E-12))) + 1] if fraction < 1 else keep
    keep = np.sort(keep)
    info = dict(info, captured=float(np.sum(weights[keep])/np.sum(weights)),
                orders=[(l, m) for l in range(Lx + 1)
                        for m in range(1 if one_d else Ly + 1)])
    info["orders"] = [info["orders"][i] for i in keep]
    return Ensemble([fields[i] for i in keep], weights[keep], power, label, info)


def gaussian_schell(sigma_s, sigma_g, wavelength, x, y=None, n=1.0, distance=0.0,
                    sigma_g_y=None, polarization="x", power=1.0, fraction=0.999,
                    max_order=60):
    """Gaussian Schell model source as an ensemble of its coherent modes.

    The cross spectral density is separable in x and y,
    W = W_x(x1, x2) W_y(y1, y2), each factor as in gsm_parameters(). The
    modes are TEM_lm Hermite-Gaussian beams with the weights
    kappa_x**l kappa_y**m; the strongest modes that carry `fraction` of the
    power are kept.

    Parameters
    ----------
    sigma_s : number
        Rms width of the irradiance at the waist.
    sigma_g : number
        Rms coherence width at the waist (along x; along y: sigma_g_y).
    wavelength : number
    x, y : arrays
        Grid of the source plane (y None: one-dimensional).
    n : number, optional
    distance : number, optional
        Distance of the source plane behind the waist.
    sigma_g_y : number, optional
        Coherence width along y (default sigma_g).
    polarization : optional
    power : number, optional
    fraction : float, optional
        Share of the power that the kept modes must carry.
    max_order : int, optional
        Highest mode order per axis.

    Returns
    -------
    Ensemble
        info holds w0, kappa (per axis), M2 and the captured power.
    """
    w0, kx = gsm_parameters(sigma_s, sigma_g)
    sgy = sigma_g if sigma_g_y is None else sigma_g_y
    _, ky = gsm_parameters(sigma_s, sgy)
    info = {"sigma_s": sigma_s, "sigma_g": (sigma_g, sgy), "w0": w0, "kappa": (kx, ky),
            "M2": (gsm_m2(sigma_s, sigma_g), gsm_m2(sigma_s, sgy))}
    return _hg_ensemble(w0, kx, wavelength, x, y, n, distance, polarization, power, fraction,
                        max_order, "Gaussian Schell model", info, kappa_y=ky)


def multimode_laser(W, M2, wavelength, x, y=None, n=1.0, distance=0.0, modes=None,
                    polarization="x", power=1.0, fraction=0.999, max_order=60):
    """Multimode laser beam as an incoherent sum of Hermite-Gaussian modes.

    With `modes` None the mode powers follow a thermal (geometric)
    distribution p_l ~ kappa**l per axis with kappa = (M² - 1)/(M² + 1), which
    gives exactly the beam quality M² and the second-moment (1/e**2)
    radius W at the waist: the embedded Gaussian has w0 = W/sqrt(M²). This
    is the Gaussian Schell model beam (Gori 1980) with sigma_s = W/2.

    Parameters
    ----------
    W : number
        Second-moment beam radius at the waist (for explicit modes: the
        waist w0 of the embedded Gaussian).
    M2 : number or pair
        Beam quality (x, y); ignored with explicit modes.
    wavelength : number
    x, y : arrays
    n, distance, polarization, power : optional
        As in gaussian_schell().
    modes : dict, optional
        Explicit mode powers {(l, m): p} (for one-dimensional fields
        {l: p} or {(l, 0): p}).
    fraction, max_order : optional
        Truncation of the thermal distribution.

    Returns
    -------
    Ensemble
    """
    if modes is not None:
        w0 = W
        fields, weights, orders = [], [], []
        for key, p in modes.items():
            l, m = (key, 0) if np.ndim(key) == 0 else key
            fields.append(hermite_gauss(l, m, w0, wavelength, x, y, n, distance,
                                        polarization=polarization))
            weights.append(p)
            orders.append((l, m))
        M2x = sum(p*(2*l + 1) for (l, m), p in zip(orders, weights))/sum(weights)
        M2y = sum(p*(2*m + 1) for (l, m), p in zip(orders, weights))/sum(weights)
        return Ensemble(fields, weights, power, "multimode laser",
                        {"w0": w0, "orders": orders, "M2": (M2x, M2y)})
    M2x, M2y = (M2, M2) if np.ndim(M2) == 0 else M2
    if min(M2x, M2y) < 1:
        raise ValueError("M2 must be >= 1")
    kx = (M2x - 1)/(M2x + 1)
    ky = (M2y - 1)/(M2y + 1)
    w0x = W/np.sqrt(M2x)
    w0y = W/np.sqrt(M2y)
    info = {"W": W, "w0": (w0x, w0y), "kappa": (kx, ky), "M2": (M2x, M2y)}
    return _hg_ensemble(w0x, kx, wavelength, x, y, n, distance, polarization, power, fraction,
                        max_order, "multimode laser", info, w0_y=w0y, kappa_y=ky)


def coherent(field, power=1.0):
    """A single (fully coherent) field as an ensemble."""
    return Ensemble([field], [1.0], power, "coherent")



C_MM_PER_FS = 299792458.0*1E3*1E-15   # speed of light in mm/fs


# --------------------------------------------------------------------------
# ensembles
# --------------------------------------------------------------------------

class Ensemble(object):
    """Mutually incoherent modes of a source.

    Parameters
    ----------
    fields : sequence of Field
        The modes; each is normalized to unit power.
    weights : sequence of float
        Power of each mode (normalized to sum to 1; the source power is
        `power`).
    power : number, optional
        Total power of the source.
    label : str, optional
    info : dict, optional
        Parameters of the source model (for the record).
    """

    coherent = False

    def __init__(self, fields, weights=None, power=1.0, label="ensemble", info=None):
        fields = list(fields)
        if not fields:
            raise ValueError("an ensemble needs at least one field")
        if weights is None:
            weights = np.ones(len(fields))
        weights = np.asarray(weights, dtype=float)
        if weights.shape != (len(fields),):
            raise ValueError("one weight per field")
        if np.any(weights < 0) or not np.sum(weights) > 0:
            raise ValueError("weights must be non-negative and not all zero")
        self.fields = [_unit_power(f) for f in fields]
        self.weights = weights/np.sum(weights)
        self.power = float(power)
        self.label = label
        self.info = dict(info or {})

    def __len__(self):
        return len(self.fields)

    def __iter__(self):
        return iter(zip(self.fields, self.weights))

    def __repr__(self):
        wls = sorted({f.wavelength for f in self.fields})
        return "{}({!r}: {} modes, {} wavelength(s))".format(
            type(self).__name__, self.label, len(self), len(wls))

    @property
    def wavelengths(self):
        return np.array([f.wavelength for f in self.fields])

    def truncated(self, fraction=0.999):
        """The strongest modes that carry `fraction` of the power."""
        order = np.argsort(-self.weights)
        n = int(np.searchsorted(np.cumsum(self.weights[order]), fraction*(1 - 1E-12))) + 1
        keep = np.sort(order[:n])
        return type(self)._like(self, keep)

    @classmethod
    def _like(cls, ens, keep):
        out = Ensemble([ens.fields[i] for i in keep], ens.weights[keep], ens.power, ens.label,
                       ens.info)
        return out


def _unit_power(field):
    P = field.power()
    if not P > 0:
        raise ValueError("a mode has no power on its grid")
    return field._with(field._A/np.sqrt(P))


class Pulse(Ensemble):
    """Mutually coherent spectral fields of a pulse.

    Parameters
    ----------
    fields : sequence of Field
        One field per (vacuum) wavelength, normalized to unit power.
    amplitudes : sequence of complex
        Spectral amplitudes a_j (their phase is the spectral phase).
    center_wavelength : number
        Carrier wavelength: the envelope is relative to exp(-i omega_0 t).
    power : number, optional
        Energy of the pulse (the time integral of the power).
    label, info : optional
    """

    coherent = True

    def __init__(self, fields, amplitudes, center_wavelength, power=1.0, label="pulse",
                 info=None):
        amplitudes = np.asarray(amplitudes, dtype=complex)
        super().__init__(fields, np.abs(amplitudes)**2, power, label, info)
        self.amplitudes = amplitudes/np.sqrt(np.sum(np.abs(amplitudes)**2))
        self.center_wavelength = float(center_wavelength)

    @property
    def omegas(self):
        """Angular frequencies (rad/fs)."""
        return 2*np.pi*C_MM_PER_FS/self.wavelengths

    @property
    def omega0(self):
        return 2*np.pi*C_MM_PER_FS/self.center_wavelength

    @classmethod
    def _like(cls, ens, keep):
        return Pulse([ens.fields[i] for i in keep], ens.amplitudes[keep], ens.center_wavelength,
                     ens.power, ens.label, ens.info)

    def time_window(self):
        """Length of the periodic time window 2*pi/d_omega (fs) of the
        (equidistant) frequency samples."""
        w = np.sort(self.omegas)
        return 2*np.pi/np.median(np.diff(w)) if len(w) > 1 else np.inf



def point_source(position, distance, wavelength, x, y=None, n=1.0, m=0.0, na=None,
                 polarization="x", z=0.0):
    """Spherical wave of a point emitter, sampled in a plane.

    The emitter sits at (x0, y0) a distance d in front of the plane. The
    field is ::

        E = cos(theta)**(m/2) exp(i k r)/r,   r = sqrt((x - x0)**2 + (y - y0)**2 + d**2),

    (radiant intensity ~ cos(theta)**m: m = 0 isotropic, m = 1
    Lambertian), with the paraxial part of k r kept analytic (alpha =
    k/(2 d), beta = -k x0/d) and only the small higher order residual
    sampled. A numerical aperture na cuts the emission off smoothly.

    Parameters
    ----------
    position : number or pair
        Emitter position (x0, y0) (a number for one-dimensional fields: a
        line source, whose field is the cylindrical wave
        ``H_0(k r) ~ exp(i k r)/sqrt(r)``).
    distance : number
        Distance d > 0 of the plane from the emitter.
    wavelength : number
    x, y : arrays
    n : number, optional
    m : number, optional
        Exponent of the emission pattern.
    na : number, optional
        Emission cut-off n*sin(theta).
    polarization, z : optional

    Returns
    -------
    Field (unit power)
    """
    k = wavenumber(wavelength, n)
    d = float(distance)
    if not d > 0:
        raise ValueError("distance must be positive")
    one_d = y is None
    x0, y0 = (position, 0.0) if np.ndim(position) == 0 else position
    if one_d:
        X = np.asarray(x, dtype=float)
        Y = np.zeros_like(X)
    else:
        X, Y = np.meshgrid(x, y)
    rho2 = (X - x0)**2 + (Y - y0)**2
    r = np.sqrt(rho2 + d**2)
    cos_t = d/r
    paraxial = d + rho2/(2*d)
    amp = cos_t**(m/2)*(1/np.sqrt(r) if one_d else 1/r)
    if na is not None:
        s = np.sqrt(1 - cos_t**2)*n
        width = 0.02*na
        amp = amp*0.5*(1 - np.tanh((s - na)/width))
    A = amp*np.exp(1j*k*(r - paraxial))
    alpha = (k/(2*d), 0.0 if one_d else k/(2*d))
    beta = (-k*x0/d, 0.0 if one_d else -k*y0/d)
    gamma = k*(d + (x0**2 + y0**2)/(2*d))
    f = _ft.Field(A, x, y, wavelength, n, alpha=alpha, beta=beta, gamma=gamma,
                  jones=_ft._normalize_jones(polarization), z=z)
    return _unit_power(f)


def extended_source(positions, distance, wavelength, x, y=None, weights=None, n=1.0, m=0.0,
                    na=None, polarization="x", power=1.0, label="extended source"):
    """Incoherent extended source: mutually incoherent point emitters.

    Parameters
    ----------
    positions : array
        Emitter positions, shape (N, 2) (or (N,) for one-dimensional fields).
    distance : number
        Distance of the field plane from the source plane.
    wavelength : number
    x, y : arrays
    weights : array, optional
        Power of each emitter (default equal).
    n, m, na, polarization : optional
        As in point_source().
    power : number, optional
    label : str, optional

    Returns
    -------
    Ensemble
    """
    positions = np.asarray(positions, dtype=float)
    fields = [point_source(p if positions.ndim == 1 else tuple(p), distance, wavelength, x, y,
                           n, m, na, polarization) for p in positions]
    return Ensemble(fields, weights, power, label,
                    {"positions": positions, "distance": distance, "m": m})


def lambertian_disk(radius, distance, wavelength, x, y=None, n_points=200, n=1.0, m=1.0,
                    na=None, polarization="x", power=1.0, rng=None):
    """Uniform Lambertian disk (an LED die, a star) of the given radius as
    an incoherent ensemble of point emitters on a sunflower (Vogel) spiral,
    the most even sampling of a disk (for one-dimensional fields: a strip of
    half width `radius`, equidistant points).

    Parameters
    ----------
    radius : number
    distance : number
        Distance of the field plane.
    wavelength : number
    x, y : arrays
    n_points : int, optional
    n, m, na, polarization, power : optional
        As in point_source() (m = 1: Lambertian).
    rng : optional
        Seed or Generator: random rotation of the spiral.

    Returns
    -------
    Ensemble
    """
    if y is None:
        pos = (np.arange(n_points) + 0.5)/n_points*2*radius - radius
        return extended_source(pos, distance, wavelength, x, None, None, n, m, na, polarization,
                               power, "Lambertian strip")
    j = np.arange(n_points) + 0.5
    r = radius*np.sqrt(j/n_points)
    rot = 0.0 if rng is None else np.random.default_rng(rng).uniform(0, 2*np.pi)
    phi = j*np.pi*(3 - np.sqrt(5)) + rot
    pos = np.stack([r*np.cos(phi), r*np.sin(phi)], axis=1)
    return extended_source(pos, distance, wavelength, x, y, None, n, m, na, polarization,
                           power, "Lambertian disk")



"""Partially coherent, polychromatic and pulsed sources for field tracing.

A `fieldtrace.Chain` traces one harmonic field: a single wavelength and
full spatial coherence. Real sources are neither. Field tracing handles
them the way VirtualLab Fusion does (Wyrowski and Kuhn 2011, section 2):
the source is decomposed into *modes*, harmonic fields that are traced one
by one through the same chain, and the detector results are added with the
right statistics:

- **Mutually incoherent modes** (a partially coherent source, a
  multimode laser, an extended LED, or the wavelengths of a stationary
  broadband source): the irradiances add, ::

      I(r) = sum_j w_j |E_j(r)|**2,

  and so do the cross spectral densities, the mutual intensity ::

      J(r_1, r_2) = sum_j w_j E_j(r_1) . conj(E_j(r_2)),

  whose normalized form is the (equal time) degree of coherence
  mu = J(r_1, r_2)/sqrt(I(r_1) I(r_2)).
- **Mutually coherent frequencies** (a pulse): the spectral fields add
  with their complex spectral amplitudes a_j, ::

      E(r, t) = sum_j a_j E_j(r) exp(-i omega_j t),

  the time-integrated fluence again being the incoherent sum.

An `Ensemble` holds the modes (`Field` objects, normalized to unit power)
and their weights (power fractions; for a `Pulse`, complex spectral
amplitudes). `trace(chain, ensemble)` runs every mode and returns an
`EnsembleResult` with the summed quantities of every detector. The chain
can be a callable that builds the chain for a wavelength, for dispersive
media (`raytrace.System.with_wavelength()`, wavelength dependent indices).

Sources
-------
- `coherent()`: a single field (the trivial ensemble).
- `gaussian_schell()`: the Gaussian Schell model source (rms width sigma_s,
  coherence width sigma_g) through its coherent mode decomposition (Gori
  1983, Starikov and Wolf 1982): Hermite-Gaussian modes with geometrically
  decreasing weights. `gsm_parameters()`, `gsm_m2()`, `gsm_width()` give the
  analytic mode waist, weights, beam quality and far-field spread.
- `multimode_laser()`: an incoherent mixture of Hermite-Gaussian modes,
  either given explicitly or with a thermal (geometric) distribution
  matching a beam quality M² (which is the Gaussian Schell model again).
- `point_source()`: the spherical wave of a point emitter, sampled in a
  plane (exact phase, analytic quadratic part, cos^m emission);
  `extended_source()` and `lambertian_disk()` make an incoherent ensemble
  of them (an LED die, a lamp filament, a star).
- `polychromatic()`: one field per wavelength with spectral weights, e.g.
  from `gaussian_spectrum()`.
- `Pulse` / `gaussian_pulse()`: a coherent set of spectral fields with
  spectral phase (group delay dispersion); `PulseResult` evaluates the
  space-time field E(x, t) at a detector.

Conventions as in pyoptics.fieldtrace: fields vary as exp(i(k.r - omega*t)),
lengths in mm, wavelengths in vacuum, c in mm/fs for pulses
(`C_MM_PER_FS`).

References
----------
F. Gori, "Collett-Wolf sources and multimode lasers", Opt. Commun. 34, 301
(1980); F. Gori, "Mode propagation of the field generated by Collett-Wolf
Schell-model sources", Opt. Commun. 46, 149 (1983).
A. Starikov and E. Wolf, "Coherent-mode representation of Gaussian
Schell-model sources and of their radiation fields", J. Opt. Soc. Am. 72,
923 (1982).
F. Wyrowski and M. Kuhn, "Introduction to field tracing", J. Mod. Opt. 58,
449 (2011).
L. Mandel and E. Wolf, "Optical coherence and quantum optics", Cambridge
(1995), chapters 4 and 5.
"""


def trace(chain, ensemble, polarization="auto", tol=1E-2, keep=False, progress=None):
    """Trace every mode of an ensemble through a chain.

    Parameters
    ----------
    chain : Chain, list of steps, or callable
        The system. A callable chain(wavelength) returns the chain for one
        vacuum wavelength (it is called once per distinct wavelength), e.g.
        ``lambda wl: ft.Chain.from_system(lens.with_wavelength(wl), gap=1)``
        for a dispersive lens.
    ensemble : Ensemble or Pulse (or a single Field)
    polarization, tol, keep : optional
        Passed to Chain.run().
    progress : callable, optional
        progress(j, n) is called before mode j of n.

    Returns
    -------
    EnsembleResult (PulseResult for a Pulse)
    """
    if isinstance(ensemble, _ft.Field):
        ensemble = coherent(ensemble)
    cache = {}

    def chain_for(wl):
        if wl not in cache:
            c = chain(wl) if callable(chain) and not isinstance(chain, _ft.Chain) else chain
            cache[wl] = c if isinstance(c, _ft.Chain) else _ft.Chain(c)
        return cache[wl]

    results = []
    for j, f in enumerate(ensemble.fields):
        if progress is not None:
            progress(j, len(ensemble))
        results.append(chain_for(f.wavelength).run(f, polarization=polarization, tol=tol,
                                                   keep=keep))
    cls = PulseResult if isinstance(ensemble, Pulse) else EnsembleResult
    return cls(ensemble, results)


def _axis_union(axes, max_N):
    lo = min(a[0] for a in axes)
    hi = max(a[-1] for a in axes)
    d = min(_ft._spacing(a) for a in axes)
    N = int(min(max_N, np.floor((hi - lo)/d + 1.5)))
    return np.linspace(lo, hi, max(N, 2))


def field_at(field, x, y=None):
    """Complete field (E_x, E_y) of a Field at arbitrary points.

    The smooth amplitude is interpolated (bilinear) and the analytic phase
    evaluated exactly, so the result is not aliased even where the complete
    field could not be sampled on the grid. Zero outside the window.

    Parameters
    ----------
    field : Field
    x, y : arrays
        Point coordinates (broadcast together; y is ignored for a
        one-dimensional field).

    Returns
    -------
    E_x, E_y : arrays of the broadcast shape of x and y
    """
    x = np.asarray(x, dtype=float)
    y = np.zeros_like(x) if (y is None or field.one_d) else np.asarray(y, dtype=float)
    x, y = np.broadcast_arrays(x, y)
    C = field._components()
    xs, ys = field.x, field._y
    ix = (x - xs[0])/_ft._spacing(xs)
    iy = (np.full_like(x, (len(ys) - 1)/2) if field.one_d
          else (y - ys[0])/_ft._spacing(ys))
    coords = np.array([iy.ravel(), ix.ravel()])
    out = []
    for c in range(2):
        re = map_coordinates(C[:, :, c].real, coords, order=1, mode="constant", cval=0.0)
        im = map_coordinates(C[:, :, c].imag, coords, order=1, mode="constant", cval=0.0)
        out.append((re + 1j*im).reshape(x.shape))
    yy = np.zeros_like(y) if field.one_d else y
    psi = (field.alpha[0]*x**2 + field.alpha[1]*yy**2 + field.beta[0]*x + field.beta[1]*yy
           + field.gamma)
    e = np.exp(1j*psi)
    return out[0]*e, out[1]*e


class EnsembleResult(object):
    """Detector results of all modes of an ensemble and their sums.

    Attributes
    ----------
    ensemble : Ensemble
    results : list of ChainResult
        One per mode, in the order of ensemble.fields.
    """

    def __init__(self, ensemble, results):
        self.ensemble = ensemble
        self.results = results

    def __len__(self):
        return len(self.results)

    def records(self, name):
        """The DetectorRecord of every mode at detector `name`."""
        return [r[name] for r in self.results]

    def grid(self, name, max_N=2048):
        """Common detector grid: the union of the windows of all modes at
        the finest spacing (x, y; y None for one-dimensional fields)."""
        fs = [rec.field for rec in self.records(name)]
        x = _axis_union([f.x for f in fs], max_N)
        y = None if fs[0].one_d else _axis_union([f._y for f in fs], max_N)
        return x, y

    def _grid(self, name, x, y):
        if x is None:
            return self.grid(name)
        return x, y

    def _scale(self):
        return self.ensemble.power*self.ensemble.weights

    def irradiance(self, name, x=None, y=None, include_z=False):
        """Summed irradiance sum_j w_j |E_j|**2 at detector `name` (times the
        source power), on the given or the common grid.

        Parameters
        ----------
        name : str
        x, y : arrays, optional
            Grid (default: grid(name)).
        include_z : bool, optional
            Add ``|E_z|**2``.

        Returns
        -------
        I : array
        """
        x, y = self._grid(name, x, y)
        I = 0.0
        for rec, w in zip(self.records(name), self._scale()):
            I = I + w*rec.field.resample(x, y).irradiance(include_z=include_z)
        return I

    def mode_irradiances(self, name, x=None, y=None):
        """Irradiance of every mode (unweighted, unit source power), shape
        (modes, ...)."""
        x, y = self._grid(name, x, y)
        return np.array([rec.field.resample(x, y).irradiance() for rec in self.records(name)])

    def power(self, name):
        """Power at detector `name` (sum over the modes)."""
        return float(sum(w*rec.field.power() for rec, w in zip(self.records(name),
                                                                self._scale())))

    def coupling(self, name):
        """Fraction of the source power coupled into the mode of a Detector
        with the "coupling" quantity: sum_j w_j eta_j P_j."""
        return float(sum(w*rec["coupling"]*rec.field.power()
                         for rec, w in zip(self.records(name), self.ensemble.weights)))

    def mutual_intensity(self, name, ref, x=None, y=None):
        """Mutual intensity J(r, r_ref) = sum_j w_j E_j(r) . conj(E_j(r_ref)).

        Parameters
        ----------
        name : str
        ref : pair or number
            Reference point (x, y) (a number for one-dimensional fields).
        x, y : arrays, optional
            Grid of the points r (default: grid(name)).

        Returns
        -------
        J : complex array
        """
        x, y = self._grid(name, x, y)
        rx, ry = (ref, 0.0) if np.ndim(ref) == 0 else ref
        if y is None:
            X, Y = x, None
        else:
            X, Y = np.meshgrid(x, y)
        J = 0.0
        for rec, w in zip(self.records(name), self._scale()):
            Ex, Ey = field_at(rec.field, X, Y)
            rx_, ry_ = field_at(rec.field, np.array([rx]), np.array([ry]))
            J = J + w*(Ex*np.conj(rx_[0]) + Ey*np.conj(ry_[0]))
        return J

    def degree_of_coherence(self, name, ref, x=None, y=None):
        """Complex degree of coherence mu(r, r_ref) = J(r, r_ref)/sqrt(I(r) I(r_ref))
        (equal time; NaN where there is no light)."""
        x, y = self._grid(name, x, y)
        J = self.mutual_intensity(name, ref, x, y)
        rx, ry = (ref, 0.0) if np.ndim(ref) == 0 else ref
        X, Y = (x, None) if y is None else np.meshgrid(x, y)
        I = 0.0
        I_ref = 0.0
        for rec, w in zip(self.records(name), self._scale()):
            Ex, Ey = field_at(rec.field, X, Y)
            a, b = field_at(rec.field, np.array([rx]), np.array([ry]))
            I = I + w*(np.abs(Ex)**2 + np.abs(Ey)**2)
            I_ref = I_ref + w*(np.abs(a[0])**2 + np.abs(b[0])**2)
        with np.errstate(invalid="ignore", divide="ignore"):
            return J/np.sqrt(I*I_ref)

    def report(self, index=0):
        """The step report of mode `index`."""
        return self.results[index].report()


class PulseResult(EnsembleResult):
    """EnsembleResult of a Pulse: in addition the space-time field."""

    def group_delay(self, name, point=(0.0, 0.0)):
        """Group delay (fs) at a point of detector `name`: the slope
        d phase/d omega of the traced spectral phase at the carrier (a
        least squares line through the unwrapped phases; the bulk part,
        the analytic phase constant, is unwrapped by construction)."""
        phases = self._spectral_phase(name, point)
        w = self.ensemble.omegas - self.ensemble.omega0
        weights = np.abs(self.ensemble.amplitudes)
        return float(np.polyfit(w, phases, 1, w=weights)[0])

    def _spectral_phase(self, name, point):
        """Absolute phase of every traced spectral field at a point: the
        analytic constant gamma_j (absolute, never wrapped) plus the wrapped
        rest, unwrapped along the frequencies."""
        px, py = (point, 0.0) if np.ndim(point) == 0 else point
        base, rest = [], []
        for rec in self.records(name):
            f = rec.field
            Ex, Ey = field_at(f._with(f._A, gamma=0.0), np.array([px]), np.array([py]))
            rest.append(np.angle(Ex[0] if abs(Ex[0]) >= abs(Ey[0]) else Ey[0]))
            base.append(f.gamma)
        base, rest = np.array(base), np.array(rest)
        order = np.argsort(self.ensemble.omegas)
        un = np.empty_like(rest)
        un[order] = np.unwrap(rest[order])
        return base + un

    def envelope(self, name, t, x, y=None, delay=None):
        """Complex envelope E(r, tau) of the pulse at detector `name`.

        E(r, t) = sum_j a_j E_j(r) exp(-i omega_j t) is evaluated in the
        retarded time tau = t - delay relative to the carrier,
        E = exp(-i omega_0 tau)*envelope.

        Parameters
        ----------
        name : str
        t : array
            Retarded times tau (fs).
        x, y : arrays
            Points (broadcast together; y ignored for one-dimensional
            fields).
        delay : number, optional
            Reference delay (fs); default: the group delay at (0, 0).

        Returns
        -------
        E_x, E_y : complex arrays of shape t.shape + broadcast(x, y).shape,
            in units with sum over time of ``|E|**2*dt`` equal to the fluence
            (times the pulse energy).
        """
        if delay is None:
            delay = self.group_delay(name)
        t = np.asarray(t, dtype=float)
        w = self.ensemble.omegas
        dw = w - self.ensemble.omega0
        T = self.ensemble.time_window()
        norm = np.sqrt(self.ensemble.power/T) if np.isfinite(T) else np.sqrt(self.ensemble.power)
        x = np.asarray(x, dtype=float)
        Ex = Ey = 0.0
        for rec, a, wj, dwj in zip(self.records(name), self.ensemble.amplitudes, w, dw):
            ex, ey = field_at(rec.field, x, y)
            ph = np.exp(-1j*wj*delay)*np.exp(-1j*dwj*t)
            ph = ph.reshape(t.shape + (1,)*ex.ndim)
            Ex = Ex + norm*a*ph*ex
            Ey = Ey + norm*a*ph*ey
        return Ex, Ey

    def intensity(self, name, t, x, y=None, delay=None):
        """``|E_x|**2 + |E_y|**2`` of the envelope (see envelope())."""
        Ex, Ey = self.envelope(name, t, x, y, delay)
        return np.abs(Ex)**2 + np.abs(Ey)**2



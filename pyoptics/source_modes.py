def gaussian_spectrum(center_wavelength, fwhm, n=9, span=2.0):
    """Equidistant samples in frequency of a Gaussian power spectrum.

    Parameters
    ----------
    center_wavelength : number
    fwhm : number
        Full width at half maximum, in wavelength (converted to frequency
        at the centre).
    n : int, optional
        Number of samples.
    span : number, optional
        The samples cover +-span*FWHM.

    Returns
    -------
    wavelengths, weights : arrays
        Weights sum to 1.
    """
    nu0 = 1/center_wavelength
    dnu = fwhm/center_wavelength**2
    nu = nu0 + np.linspace(-span, span, n)*dnu if n > 1 else np.array([nu0])
    w = np.exp(-4*np.log(2)*((nu - nu0)/dnu)**2)
    return 1/nu, w/np.sum(w)


def polychromatic(make_field, wavelengths, weights=None, power=1.0, label="polychromatic"):
    """Stationary polychromatic source: one field per wavelength, the
    wavelengths mutually incoherent.

    Parameters
    ----------
    make_field : callable
        make_field(wavelength) returns the Field at that wavelength.
    wavelengths : array
    weights : array, optional
        Spectral power weights (default equal).
    power : number, optional
    label : str, optional

    Returns
    -------
    Ensemble
    """
    wavelengths = np.atleast_1d(np.asarray(wavelengths, dtype=float))
    return Ensemble([make_field(w) for w in wavelengths], weights, power, label,
                    {"wavelengths": wavelengths})


def gaussian_pulse(make_field, center_wavelength, tau_fwhm, n=32, span=None, gdd=0.0,
                   tod=0.0, energy=1.0):
    """Gaussian pulse as coherent spectral fields.

    The spectral amplitude is Gaussian in the angular frequency with the
    transform-limited duration tau_fwhm (of the intensity), times the
    spectral phase gdd/2*(omega - omega_0)**2 + tod/6*(omega - omega_0)**3.
    The frequencies are equidistant; the time window is
    2*pi/(omega step), see Pulse.time_window().

    Parameters
    ----------
    make_field : callable
        make_field(wavelength) returns the (spatial) Field at a wavelength.
    center_wavelength : number
        Carrier wavelength (mm).
    tau_fwhm : number
        Transform-limited duration (fs).
    n : int, optional
        Number of spectral samples.
    span : number, optional
        Half width of the sampled band in units of the spectral rms width
        of the amplitude (default 4).
    gdd, tod : number, optional
        Group delay dispersion (fs**2) and third order dispersion (fs**3).
    energy : number, optional

    Returns
    -------
    Pulse
    """
    span = 4.0 if span is None else span
    w0 = 2*np.pi*C_MM_PER_FS/center_wavelength
    # |a(omega)|**2 ~ exp(-(omega - w0)**2 tau**2/(4 ln 2)): amplitude rms width
    sigma = np.sqrt(2*np.log(2))/tau_fwhm*np.sqrt(2)
    dw = np.linspace(-span, span, n)*sigma if n > 1 else np.array([0.0])
    a = np.exp(-(dw*tau_fwhm)**2/(8*np.log(2)))*np.exp(1j*(gdd/2*dw**2 + tod/6*dw**3))
    wls = 2*np.pi*C_MM_PER_FS/(w0 + dw)
    fields = [make_field(wl) for wl in wls]
    return Pulse(fields, a, center_wavelength, energy, "Gaussian pulse",
                 {"tau_fwhm": tau_fwhm, "gdd": gdd, "tod": tod})
